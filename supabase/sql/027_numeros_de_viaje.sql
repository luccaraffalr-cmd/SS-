-- Números de viaje (19/10/2026).
-- 1) Arreglo: cada 10 minutos crear_viajes_fijos intentaba crear todos los viajes de las series aunque ya existieran
--    ("on conflict do nothing") y cada intento gastaba un número aunque no creara nada: los números saltaban de a miles
--    por día (un viaje del 19/10 era el #302361). Ahora solo intenta crear los días que faltan.
-- 2) Se renumeran los viajes que quedan (el 19/10, después de borrar todos los pasados) desde el 1, en orden de fecha,
--    y los nuevos siguen desde ahí. Lo que apunta a un viaje (ofertas, registro, avisos, cambios de pago, planilla) lo
--    sigue solo (on update cascade). El link del pasajero no cambia: usa un código aparte.
-- Se ejecuta una sola vez en Supabase → SQL Editor.

---------------------------------------------------------------------------
-- 1) crear_viajes_fijos sin gastar números (igual que en 026, salteando los días que ya tienen viaje).
---------------------------------------------------------------------------

create or replace function public.crear_viajes_fijos(p_fijo bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  f public.viajes_fijos;
  d date;
  pres timestamptz;
  nuevo bigint;
  hoy date := (now() at time zone 'America/Argentina/Buenos_Aires')::date;
begin
  select * into f from public.viajes_fijos where id = p_fijo;
  if not found or not f.activo then return; end if;

  for d in
    select x from unnest(coalesce(f.fechas, '{}'::date[])) as x where x >= hoy
    union
    select hoy + i from generate_series(0, 27) as i where f.fechas is null
    order by 1
  loop
    continue when not public.fijo_corresponde(f, d);
    -- Ya existe (aunque esté anulado): no se intenta, así no se gasta un número de viaje.
    continue when exists (select 1 from public.viajes where viaje_fijo_id = f.id and fecha_fija = d);
    pres := public.hora_argentina(d, f.hora);
    continue when pres <= now();

    nuevo := null;
    insert into public.viajes (tipo, cliente_nombre, cliente_telefono, origen, destino, observaciones,
                               hora_presentacion, hora_asignacion, creado_por,
                               viaje_fijo_id, fecha_fija, chofer_fijo, espera_gestion)
    values ('programado', f.cliente_nombre, f.cliente_telefono, f.origen, f.destino, f.observaciones,
            pres, pres - make_interval(mins => f.anticipacion), null,
            f.id, d, f.chofer_id, f.chofer_id is not null)
    on conflict (viaje_fijo_id, fecha_fija) do nothing
    returning id into nuevo;

    if nuevo is not null then
      perform public.registrar(nuevo, 'Creado solo por el viaje fijo #' || f.id, null);
    end if;
  end loop;
end;
$$;
revoke execute on function public.crear_viajes_fijos(bigint) from public, anon, authenticated;

---------------------------------------------------------------------------
-- 2) Renumerar los viajes desde el 1 (en orden de fecha).
---------------------------------------------------------------------------

do $$
declare
  c record;
  proximo bigint;
begin
  -- Lo que apunta a un viaje lo sigue si el viaje cambia de número (y se sigue borrando con él).
  for c in
    select con.conname, con.conrelid::regclass as tabla, a.attname as columna
    from pg_constraint con
    join pg_attribute a on a.attrelid = con.conrelid and a.attnum = con.conkey[1]
    where con.contype = 'f' and con.confrelid = 'public.viajes'::regclass
  loop
    execute format('alter table %s drop constraint %I', c.tabla, c.conname);
    execute format('alter table %s add constraint %I foreign key (%I) references public.viajes (id) on delete cascade on update cascade',
                   c.tabla, c.conname, c.columna);
  end loop;

  -- Sin disparadores mientras se renumera (no es un cambio del viaje: no avisa ni anota nada).
  alter table public.viajes alter column id set generated by default;
  alter table public.viajes disable trigger user;
  update public.viajes set id = -id;  -- primero a negativos, para que los números nuevos no choquen
  update public.viajes v set id = n.nuevo
  from (select id, row_number() over (order by coalesce(hora_presentacion, hora_asignacion), id) as nuevo
        from public.viajes) n
  where v.id = n.id;
  alter table public.viajes enable trigger user;

  -- Los viajes nuevos siguen desde el último.
  select coalesce(max(id), 0) + 1 into proximo from public.viajes;
  execute format('alter table public.viajes alter column id restart with %s', proximo);
  alter table public.viajes alter column id set generated always;
end $$;
